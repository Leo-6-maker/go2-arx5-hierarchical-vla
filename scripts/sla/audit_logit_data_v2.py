"""Derive TRAIN-only logit labels/statistics from qualified numeric packets.

The immutable camera and FK evidence is reused. No image, model, simulator,
future-achieved state or unconsumed label is generated by this operation.
"""
import json
from pathlib import Path
import sys
import time
import numpy as np

from scripts.pi0292.durable import write
from go2arx5_vla.sla_adapter.checkpoint_v1 import sha
from go2arx5_vla.sla_adapter.codec_v1 import Codec, Quantiles, TOLERANCES, pad32, roundtrip_error
from go2arx5_vla.sla_adapter.gripper_v2 import EPSILON, VERSION, GripLogitCodec, decode_latent
from go2arx5_vla.sla_adapter.runtime_v1 import read_pin


def run(spec):
    original = read_pin(spec['target_audit'])
    if (original['schema'] != 'SLA_TARGET_CODEC_DATA_ACTUAL_V1' or not original['passes']
            or original['expert_windows'] != 1450 or original['actual_episodes'] != 100):
        raise ValueError('REUSE_ACTUAL_FULL_V1_DATA_QUALIFICATION')
    prior = Path(spec['target_audit']['path']).parent
    frames = read_pin(dict(path=str(prior / 'FRAMES.private.json'), sha256=original['frames_sha256']))
    old_stats = read_pin(dict(path=str(prior / 'STATISTICS.private.json'), sha256=original['statistics_sha256']))
    dataset = Path(spec['dataset'])
    if sha(dataset / 'DATASET_MANIFEST.json') != original['source_dataset_sha256']:
        raise ValueError('ORIGINAL_TRAIN100_DATASET_CHANGED')
    manifest = json.loads((dataset / 'DATASET_MANIFEST.json').read_bytes())
    if len(manifest['episodes']) != 100 or any(e['split'] != 'TRAIN' for e in manifest['episodes']):
        raise ValueError('TRAIN_ONLY_DERIVED_LABELS')
    output = Path(spec['registered_root']) / 'derived'
    output.mkdir(exist_ok=False)
    states, originals, derived, physical, state10s, identities = [], [], [], [], [], []
    for episode in manifest['episodes']:
        if time.time() >= spec['deadline_epoch']:
            raise TimeoutError('FINITE_LOGIT_DATA_DERIVATION')
        path = dataset / episode['file']
        if not path.resolve().is_relative_to(dataset.resolve()) or sha(path) != episode['sha256']:
            raise ValueError('CONSUMPTION_PROVEN_NUMERIC_PACKET_CHANGED')
        with np.load(path, allow_pickle=False) as packet:
            if (packet['label_representation'].item() != 'ABSOLUTE_COMMITTED_EEF10'
                    or packet['command_period_s'].item() != .05
                    or packet['native_dt_s'].item() != .002):
                raise ValueError('ORIGINAL_NOMINAL_LABEL_AND_CLOCK_REQUIRED')
            transform = frames['episodes'][episode['id']]['T_policy_from_mount']
            raw_codec, codec = Codec(transform), GripLogitCodec(transform)
            for anchor in episode['supervised_anchors']:
                if not packet['valid_window'][anchor]:
                    raise ValueError('INTERVENTION_OR_INVALID_WINDOW_NOT_BC')
                atom = int(packet['native_command_anchor'][anchor])
                expert = packet['committed_absolute10'][atom:atom + 40].copy()
                state10 = packet['actual_state10'][anchor].copy()
                state, action = raw_codec.encode(state10, expert)
                new_state, latent = codec.encode(state10, expert)
                if not np.array_equal(state, new_state) or not np.array_equal(action[:, :6], latent[:, :6]):
                    raise ValueError('LOGIT_TRANSFORM_CHANGED_STATE_OR_POSE')
                states.append(state); originals.append(action); derived.append(latent)
                physical.append(expert); state10s.append(state10)
                identities.append(dict(episode_id=episode['id'], anchor=anchor,
                                       packet_sha256=episode['sha256']))
    states, originals, derived = map(np.stack, (states, originals, derived))
    if states.shape != (1450, 7) or derived.shape != (1450, 40, 7):
        raise ValueError('ALL1450_UNIQUE_TRAIN_WINDOWS_REQUIRED')
    statistics = dict(state=Quantiles.fit(states), actions=Quantiles.fit(derived.reshape(-1, 7)))
    for key, width in (('state', 7), ('actions', 6)):
        for quantile in ('q01', 'q99'):
            if not np.array_equal(getattr(statistics[key], quantile)[:width], np.asarray(old_stats[key][quantile])[:width]):
                raise ValueError('UNCHANGED_STATE_AND_POSE_STATISTICS_REQUIRED')
    max64 = dict(xyz_m=0., so3_rad=0., gripper=0.)
    max32 = dict(max64)
    maximum_derived_grip_error = 0.
    for i, identity in enumerate(identities):
        if time.time() >= spec['deadline_epoch']:
            raise TimeoutError('FINITE_LOGIT_ROUNDTRIP')
        codec = GripLogitCodec(frames['episodes'][identity['episode_id']]['T_policy_from_mount'])
        normalized = statistics['actions'].normalize(derived[i])
        for dtype, errors in ((np.float64, max64), (np.float32, max32)):
            reconstructed = codec.decode(state10s[i], pad32(statistics['actions'].unnormalize(normalized.astype(dtype))))
            values = roundtrip_error(physical[i], reconstructed)
            expected_grip = decode_latent(derived[i, :, 6])
            maximum_derived_grip_error = max(maximum_derived_grip_error, float(np.abs(reconstructed[:, 9] - expected_grip).max()))
            for name, value in values.items():
                errors[name] = max(errors[name], value)
                limit = EPSILON + TOLERANCES['gripper'] if name == 'gripper' else TOLERANCES[name]
                if value > limit:
                    raise ValueError('DECLARED_LOGIT_ROUNDTRIP_BOUND:' + name)
    if maximum_derived_grip_error > TOLERANCES['gripper']:
        raise ValueError('NUMERICAL_ERROR_RELATIVE_TO_DERIVED_LABEL')
    stats = dict(state=statistics['state'].summary(states),
                 actions=statistics['actions'].summary(derived.reshape(-1, 7)),
                 codec_version=VERSION, epsilon=EPSILON, normalization_before_padding=True,
                 unique_state_windows=1450, action_knots=1450 * 40)
    write(output / 'STATISTICS.private.json', stats)
    np.savez(output / 'LABELS.private.npz', state7=states, original_action7=originals,
             derived_action7=derived, original_nominal_gripper=originals[:, :, 6])
    write(output / 'LABEL_IDENTITIES.private.json', identities)
    result = dict(schema='SLA_GRIP_LOGIT_TRAIN100_DERIVATION_V2', passes=True,
                  plan_revision=spec['scaleup_plan_revision'], original_target_audit=spec['target_audit'],
                  source_dataset_sha256=original['source_dataset_sha256'], codec_version=VERSION,
                  epsilon=EPSILON, expert_windows=1450, episodes=100, action_knots=58000,
                  original_labels_preserved=True, original_source_packets_modified=False,
                  state_statistics_unchanged=True, pose_action_statistics_unchanged=True,
                  state_input_gripper_transform=False, original_FK_and_RGB_qualification_reused=True,
                  original_frames_sha256=original['frames_sha256'], original_statistics_sha256=original['statistics_sha256'],
                  statistics_sha256=sha(output / 'STATISTICS.private.json'),
                  labels_sha256=sha(output / 'LABELS.private.npz'), identities_sha256=sha(output / 'LABEL_IDENTITIES.private.json'),
                  FP64_original_label_max_error=max64, FP32_original_label_max_error=max32,
                  maximum_numerical_gripper_error_relative_to_derived_label=maximum_derived_grip_error,
                  original_zero_gripper_labels=int((originals[:, :, 6] == 0).sum()),
                  original_one_gripper_labels=int((originals[:, :, 6] == 1).sum()),
                  original_endpoint_bias_bound=EPSILON,
                  model_loads=0, model_calls=0, optimizer_updates=0, optimization_visits=0,
                  new_image_decodes=0, new_FK_calls=0, physical_requests=0, native_integrations=0,
                  DEV_TEST_reads=0, native_expert_bias_validation='NOT_RUN', training_admitted=False)
    if sha(dataset / 'DATASET_MANIFEST.json') != result['source_dataset_sha256']:
        raise ValueError('SOURCE_CHANGED_DURING_DERIVATION')
    write(output / 'RESULT.private.json', result)
    write(Path(spec['registered_root']) / 'RESULT.private.json', result)
    return result


if __name__ == '__main__':
    run(json.loads(Path(sys.argv[1]).read_bytes()))
